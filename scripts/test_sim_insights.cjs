'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const html=fs.readFileSync('docs/index.html','utf8');
assert(html.includes('id="simInsights"'),'Insights UI missing');
const start=html.indexOf('function rng(seed)'),end=html.indexOf('\nfunction resultOfScore(',start);
assert(start>=0&&end>start,'Simulation functions missing');
const context={clamp:(x,low,high)=>Math.min(high,Math.max(low,x))};
vm.runInNewContext(html.slice(start,end)+';globalThis.testSim=simulate;',context);
const p={lh:1.55,la:1.2,eh:1500,ea:1390};
const r=context.testSim(p,{ht_n:0},{ht_n:0},100000);
const sum=rows=>rows.reduce((acc,x)=>acc+x.count,0);
assert.equal(r.n,100000);
assert.equal(sum(r.simBreakdown.results),100000,'1-X-2 counts mismatch');
assert.equal(sum(r.simBreakdown.goals),100000,'Goal distribution mismatch');
assert.equal(r.allScores.reduce((a,x)=>a+x.number,0),100000,'Exact-score counts mismatch');
assert.equal(r.simBreakdown.events.every(x=>x.count>=0&&x.count<=100000),true);
assert.equal(r.simBreakdown.scores[0].count,r.allScores[0].number);
for(const k of ['1','X','2']) assert(Math.abs(r.markets[k]-r.simBreakdown.results.find(x=>x.key===k).p)<1e-8);
const r2=context.testSim(p,{ht_n:0},{ht_n:0},100000);
assert.equal(JSON.stringify(r.simBreakdown.results),JSON.stringify(r2.simBreakdown.results));
console.log('FUTSIM 100,000 simulation count invariants: OK');
