const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync('docs/index.html','utf8');
const start=html.indexOf('function preserveAdvancedTeamMetrics(');
const end=html.indexOf('function hydrateMatches(',start);
assert(start>0&&end>start,'Advanced-metric preservation helper must exist');
assert(html.includes('t.stats=preserveAdvancedTeamMetrics(t.stats,live)'),'Live CSV hydration must call preservation helper');
assert(html.includes('id="xgReadout"'),'Top-level xG coverage must be visible');
const scope=vm.createContext({});
const preserve=vm.runInContext(html.slice(start,end)+'; preserveAdvancedTeamMetrics',scope);
const prev={matches:8,xg:1.296,xa:0.627,xg_total:9.07,xa_total:4.39,xga:null};
const newStats={matches:9,gf:2.1,ga:1.2,corners:5.1};
const merged=preserve(prev,newStats);
assert.equal(merged.xg,1.296);
assert.equal(merged.xa,0.627);
assert.equal(merged.xg_total,9.07);
assert.equal(merged.xa_total,4.39);
assert.equal(merged.matches,9);
assert.equal(merged.gf,2.1);
assert.equal(merged.xga,undefined);
const missing=preserve({xg:null,xa:undefined},{matches:2,gf:0});
assert.equal(missing.xg,undefined);
assert.equal(missing.xa,undefined);
assert(html.includes("xG/maç")&&html.includes("xA/maç"),'Team-level xG/xA must be labeled');
console.log('FUTSIM xG merge regression: OK; measured xG/xA survive CSV refresh, missing data never converted to zero.');
